// Regenerate from static headings, never from HTML embedded inside JavaScript.
// Default: verify. --write: regenerate. --patch: print an apply_patch-compatible update.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const target = 'docs/assets/search-index.js';
const before = fs.readFileSync(path.join(root, target), 'utf8').replace(/\r\n/g, '\n');
const context = {window: {}};
vm.runInNewContext(before, context);
const sections = new Map(context.window.KYTY_INDEX.map(e => [e.f, e.s]));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'docs/content/learning.json'), 'utf8'));
const beginnerPages = new Set(manifest.topics.filter(t => t.level === 'beginner').map(t => t.file));
const decode = s => s.replace(/<[^>]*>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
  .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'")
  .replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const entries = [];
for (const file of fs.readdirSync(path.join(root, 'docs')).filter(f => f.endsWith('.html')).sort()) {
  const html = fs.readFileSync(path.join(root, 'docs', file), 'utf8')
    .replace(/<!--[^]*?-->|<script\b[^]*?<\/script>|<style\b[^]*?<\/style>/gi, '');
  for (const m of html.matchAll(/<h([1-6])\b[^>]*\bid="([^"]+)"[^>]*>([^]*?)<\/h\1>/gi)) {
    const developerPages = ['developer-curriculum.html', 't-trace-boot.html', 't-trace-draw.html', 't-debugging-labs.html'];
    entries.push({t: decode(m[3]), f: file, a: m[2], s: beginnerPages.has(file) ? 'BEGINNER' : developerPages.includes(file) ? 'DEVELOPER' : sections.get(file) || (file.startsWith('t-') ? 'TOPIC' : 'TOOL')});
  }
}
const after = '/* generated by scripts/build-search-index.cjs */\nwindow.KYTY_INDEX = [\n' +
  entries.map(e => '  '+JSON.stringify(e)).join(',\n') + '\n];\n';
if (process.argv.includes('--patch')) {
  const patch = '*** Begin Patch\n*** Update File: '+target+'\n@@\n' +
    before.trimEnd().split('\n').map(l => '-'+l).join('\n')+'\n'+
    after.trimEnd().split('\n').map(l => '+'+l).join('\n')+'\n*** End Patch';
  const offset = Number(process.argv.find(a => a.startsWith('--offset='))?.split('=')[1] || 0);
  if (process.argv.includes('--length')) console.log(patch.length);
  else process.stdout.write(process.argv.some(a => a.startsWith('--offset=')) ? patch.slice(offset, offset + 40000) : patch);
} else if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(root, target), after);
  console.log('Wrote '+entries.length+' searchable headings.');
} else if (before !== after) {
  console.error('Search index is stale. Regenerate with --write or review the update with --patch.');
  process.exitCode = 1;
} else console.log(`PASS: ${entries.length} searchable headings match the current HTML.`);
