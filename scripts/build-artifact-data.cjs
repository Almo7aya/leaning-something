// Snapshot numeric names from the same source revision as the lessons.
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const root = path.resolve(__dirname, '..');
const source = path.resolve(process.env.KYTY_SOURCE_DIR || path.join(root, 'KytyPS5'));
const revision = require('../docs/content/learning.json').project.revision;
if (!fs.existsSync(path.join(source, 'src'))) {
  console.log('SKIP: artifact table source unavailable; committed tables remain usable.');
  process.exit(0);
}
if (cp.execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== revision)
  throw new Error('Artifact table generation requires the pinned learning.json revision.');
const read = name => fs.readFileSync(path.join(source, 'src', name), 'utf8');
const data = {revision, instructions:{}, pm4:{}, bufferFormats:{}, spirv:{}};
const grammar = JSON.parse(fs.readFileSync(path.join(source, '3rdparty/SPIRV-Headers/include/spirv/unified1/spirv.core.grammar.json'), 'utf8'));
for (const instruction of grammar.instructions) data.spirv[instruction.opcode] = instruction.opname;
for (const name of ['ScalarAluOps', 'VectorAluOps', 'MemoryOps', 'ImageOps']) {
  const text = read('graphics/shader/recompiler/frontend/decode/'+name+'.cpp');
  for (const match of text.matchAll(/(\w+)_OPCODE_LIST\[\]\s*=\s*\{([^]*?)\n\};/g)) {
    const table = data.instructions[match[1]] = {};
    for (const entry of match[2].matchAll(/\{(0x[0-9a-f]+|\d+)u?,\s*Opcode::(\w+)/gi))
      table[Number(entry[1])] = entry[2].toLowerCase();
  }
}
for (const entry of read('graphics/guest_gpu/pm4.h').matchAll(/constexpr uint32_t (IT_\w+)\s*=\s*(0x[0-9a-f]+|\d+);/gi))
  data.pm4[Number(entry[2])] = entry[1];
const formats = read('graphics/guest_gpu/gpu_defs.h').match(/enum class BufferFormat[^]*?\{([^]*?)\};/)[1];
for (const entry of formats.matchAll(/(k\w+)\s*=\s*(0x[0-9a-f]+|\d+)/gi))
  data.bufferFormats[Number(entry[2])] = entry[1];
for (const family of ['SOP1','SOP2','SOPC','SOPK','SOPP','VOP1','VOP2','VOPC'])
  if (!Object.keys(data.instructions[family] || {}).length) throw new Error('Missing opcode table '+family);
const output = '// Generated by scripts/build-artifact-data.cjs; do not edit.\n' +
  '(function(root,data){if(typeof module==="object"&&module.exports)module.exports=data;else root.KYTY_ARTIFACT_DATA=data;})(typeof window==="object"?window:globalThis,\n'+JSON.stringify(data,null,2)+');\n';
const target = path.join(root, 'docs/assets/artifact-data.js');
if (process.argv.includes('--write')) fs.writeFileSync(target, output);
else if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) throw new Error('Stale artifact tables; run with --write.');
console.log('PASS: artifact opcode and format tables match '+revision.slice(0,8)+'.');
